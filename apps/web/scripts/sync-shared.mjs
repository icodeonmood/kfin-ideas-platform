// Copies shared YAML sources into JSON the web app imports (browser and server alike):
//   services/worker/pii/patterns.yaml -> src/lib/pii/patterns.json   (BLD-005, BLD-030)
//   policy/rbac.yaml                  -> src/lib/rbac.json           (BLD-040)
// and the 1% Club enums (E-ENUMS) from one JSON source to both sides (BLD-E006 cut-over):
//   contracts/1pc/enums.json -> src/lib/contracts/enums.gen.ts   (as const, so the unions are derived)
//                            -> services/worker/onepc/enums.json (the worker image carries no contracts/)
// Run `npm run sync:shared` after editing any source. Unit tests fail if a copy drifts from its source.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const pairs = [
  ["services/worker/pii/patterns.yaml", "apps/web/src/lib/pii/patterns.json"],
  ["policy/rbac.yaml", "apps/web/src/lib/rbac.json"],
];
for (const [from, to] of pairs) {
  const data = parse(readFileSync(path.join(repo, from), "utf8"));
  writeFileSync(path.join(repo, to), JSON.stringify(data, null, 2) + "\n");
  process.stdout.write(`${from} -> ${to}\n`);
}

const enumsFrom = "contracts/1pc/enums.json";
const enums = JSON.parse(readFileSync(path.join(repo, enumsFrom), "utf8"));
const generated =
  "// Generated by `npm run sync:shared` from contracts/1pc/enums.json (E-ENUMS). Do not edit by hand.\n" +
  `export const ONEPC = ${JSON.stringify(enums, null, 2)} as const;\n`;
for (const [to, text] of [
  ["apps/web/src/lib/contracts/enums.gen.ts", generated],
  ["services/worker/onepc/enums.json", JSON.stringify(enums, null, 2) + "\n"],
]) {
  mkdirSync(path.dirname(path.join(repo, to)), { recursive: true });
  writeFileSync(path.join(repo, to), text);
  process.stdout.write(`${enumsFrom} -> ${to}\n`);
}
